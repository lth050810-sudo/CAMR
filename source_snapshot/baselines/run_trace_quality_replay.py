from baselines.common import append_jsonl  # noqa: E402


def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument('--task', choices=TASKS, required=True)
    p.add_argument('--output-dir', type=Path, required=True)
    p.add_argument('--micro-tokens', type=int, default=8192)
    p.add_argument('--pool-per-stage', type=int, default=512)
    p.add_argument('--replay-k', type=int, default=4)
    p.add_argument('--quality-fraction', type=float, default=0.5)
    p.add_argument('--duplicate-fraction', type=float, default=0.0,
                   help='Reserve this fraction of K4 for exact repeated current facts.')
    p.add_argument('--smoke', action='store_true')
    args = p.parse_args()
    if not 0 <= args.quality_fraction <= 1 or not 0 <= args.duplicate_fraction <= 1:
        p.error('quality and duplicate fractions must be in [0, 1]')
    if args.quality_fraction + args.duplicate_fraction > 1:
        p.error('quality and duplicate fractions cannot exceed one')
    return args


def load_data(task, smoke=False):
    payload = json.loads((SUITE / 'manifests' / f'{task}.json').read_text())
    train = payload['train']
    if smoke:
        train = [dict(r, stage=i // 20 + 1) for i, r in enumerate(train[:40])]
        payload = dict(payload, train=train, test=payload['test'][:8])
    return train, payload


