#!/usr/bin/env python3
"""TRACE quality-filtered replay control.

This runner is an isolated V5 candidate.  It keeps the full-parameter TRACE
backend and one optimizer step per incoming fact, but replaces V4's online
actor-critic action/target sampler with stage-boundary on-policy quality
filtering.  A replay row stores the answer generated by the previous stage
checkpoint; only the highest-scoring generated rows are admitted.  Half of a
K4 batch remains uniform gold-history replay so the candidate retains a
strong random-replay floor and broad coverage.
"""
