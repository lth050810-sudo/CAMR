def quality_replay_row(row, prediction, score):
    replay = copy.deepcopy(row)
    # A perfect task score certifies the gold answer.  Preserve the canonical
    # training target in that case instead of storing harmless generation
    # formatting (leading spaces, explanations, or code whitespace) as a new
    # target.  Non-perfect admitted rollouts remain genuinely on-policy.
    replay['ans'] = row['ans'] if float(score) >= 100.0 else prediction
    replay['_quality_score'] = float(score)
    replay['_replay_origin'] = 'on_policy_generated'
    replay['_replay_gold'] = row['ans']
    return replay


def choose_replay(seen, quality_pool, rng, k, quality_fraction,
                  preferred=None, duplicate_fraction=0.0):
    if not seen or not k:
        return []
    quality_n = min(len(quality_pool), int(round(k * quality_fraction)))
    duplicate_n = min(k - quality_n, int(round(k * duplicate_fraction)))
    uniform_n = k - quality_n - duplicate_n
    selected = []
    used = set()
    if quality_n:
        # Quality pool is already stage-balanced and score sorted.  Randomly
        # sample from the admitted tail so one high-scoring prompt is not
        # replayed on every event.
        qpool = quality_pool[:]
        chosen = rng.sample(qpool, min(quality_n, len(qpool)))
        selected.extend(chosen)
        used.update(str(r['sample_id']) for r in chosen)
    # Keep the two sources disjoint.  Otherwise a row that happens to be in
    # the quality pool can be selected again by the uniform branch and silently
    # push the effective quality fraction above the configured value.
    quality_ids = {str(r['sample_id']) for r in quality_pool}
    available = [r for r in seen
                 if str(r['sample_id']) not in used
                 and str(r['sample_id']) not in quality_ids]
    duplicate_selected = 0
    if duplicate_n and preferred is not None:
        duplicate_rows = [r for r in available
                          if r.get('update') == preferred.get('update')
                          and r.get('ans') == preferred.get('ans')]
        chosen = rng.sample(duplicate_rows, min(duplicate_n, len(duplicate_rows)))
        selected.extend(dict(r, _replay_origin='exact_duplicate') for r in chosen)
        duplicate_selected = len(chosen)
        used.update(str(r['sample_id']) for r in chosen)
        available = [r for r in available if str(r['sample_id']) not in used]
    uniform_n += duplicate_n - duplicate_selected
    if uniform_n:
        selected.extend(rng.sample(available, min(uniform_n, len(available))))
    return selected


def admit_quality_pool(task, rows, predictions, pool_per_stage):
    records = []
    for row, prediction in zip(rows, predictions):
        score, invalid = sample_score(task, row['ans'], prediction, row['update'])
        if invalid or not prediction.strip():
            continue
        records.append((float(score), quality_replay_row(row, prediction, score)))
    records.sort(key=lambda item: item[0], reverse=True)
    return [row for _, row in records[:pool_per_stage]], records


def run(opts, driver, train, payload):
    out = opts.output_dir
    if out.exists() and any(out.iterdir()):
        raise FileExistsError(f'non-empty output directory: {out}')
    out.mkdir(parents=True, exist_ok=True)
    evaluator = Evaluation(opts, payload, out, len(train))
    # Match Random Full K4's replay RNG stream during stage 1.  The first
    # 1,000 events therefore have identical uniform history draws; later
    # stages diverge only when quality-filtered replay is introduced.
    rng = random.Random(42 + 9001)
    stages = sorted({int(row['stage']) for row in train})
    seen = []
    quality_pool = []
    quality_records = []
    actions = []
    totals = {'events': 0, 'current_presentations': 0, 'replay_presentations': 0,
              'optimizer_steps': 0, 'quality_replay_presentations': 0,
              'uniform_replay_presentations': 0}
    stage_rows = {stage: [r for r in train if int(r['stage']) == stage] for stage in stages}
    started = time.perf_counter()
    atomic(out / 'run_config.json', {
        'method': 'ours_v5_quality_replay', 'task': opts.task,
        'mode': 'stage_quality_replay', 'parameter_mode': 'full',
        'training_loss': 'token_mean', 'training_views': 1,
        'learning_rate': 2e-6, 'replay_k': opts.replay_k,
        'quality_fraction': opts.quality_fraction,
        'duplicate_fraction': opts.duplicate_fraction,
        'pool_per_stage': opts.pool_per_stage,
        'replay_rng_seed': 42 + 9001,
        'no_ignore': True, 'fresh_base': True,
        'quality_metric': 'TRACE training metric via sample_score',
        'on_policy_target': 'previous-stage greedy generated answer',
        'perfect_score_target': 'gold canonical answer',
        'train_rows': len(train), 'stage_sizes': {str(k): len(v) for k, v in stage_rows.items()},
        'backend': driver.backend.metadata,
    })
    atomic(out / 'selected_stream.json', train)

    for stage in stages:
        for row in stage_rows[stage]:
            replay = choose_replay(
                seen, quality_pool, rng, opts.replay_k, opts.quality_fraction,
                preferred=row, duplicate_fraction=opts.duplicate_fraction)
            replay_ids = {str(r['sample_id']) for r in replay}
            quality_ids = {str(r['sample_id']) for r in quality_pool}
            quality_count = sum(r.get('_replay_origin') == 'on_policy_generated' for r in replay)
            training_rows = [dict(row)] + replay
            stats = driver.train(training_rows, 1)
            seen.append(dict(row))
            record = {
                'event': totals['events'], 'stage': stage, 'sample_id': row['sample_id'],
                'replay_ids': [r['sample_id'] for r in replay],
                'replay_quality_count': quality_count,
                'replay_uniform_count': len(replay) - quality_count,
                'replay_origins': [r.get('_replay_origin', 'gold_uniform') for r in replay],
                'train': stats,
            }
            actions.append(record)
            append_jsonl(out / 'actions.jsonl', [record])
            totals['events'] += 1
            totals['current_presentations'] += 1
            totals['replay_presentations'] += len(replay)
            totals['quality_replay_presentations'] += quality_count
            totals['uniform_replay_presentations'] += len(replay) - quality_count
            totals['optimizer_steps'] += stats['optimizer_steps']
            if totals['events'] % 10 == 0:
                atomic(out / 'progress.json', {
                    'status': 'training', 'stage': stage, 'events': totals['events'],
                    'total_events': len(train), 'totals': totals,
                    'elapsed_seconds': time.perf_counter() - started,
                })

        # Build the next-stage replay buffer from the previous checkpoint.
        generated = driver.generate([r['update'] for r in stage_rows[stage]])
        admitted, scored = admit_quality_pool(opts.task, stage_rows[stage], generated, opts.pool_per_stage)
        quality_pool.extend(admitted)
        # Keep the strongest rows from every observed stage, with stage quotas
        # preventing a single easy block from taking over the buffer.
        by_stage = {}
        for r in quality_pool:
            by_stage.setdefault(int(r['stage']), []).append(r)
        quality_pool = []
        for s in sorted(by_stage):
            group = sorted(by_stage[s], key=lambda r: float(r.get('_quality_score', 0)), reverse=True)
            quality_pool.extend(group[:opts.pool_per_stage])
        # Keep a durable audit record for every non-empty, valid rollout.  The
        # sorted ``scored`` list is not aligned with the input rows, so derive
        # this from the admitted records instead of indexing it by row offset.
        quality_records.extend(
            {'stage': stage, 'sample_id': r['sample_id'],
             'prediction': r['ans'], 'score': float(r['_quality_score'])}
            for r in admitted
        )
        append_jsonl(out / 'quality_rollouts.jsonl', [
            {'stage': stage, 'sample_id': r['sample_id'], 'prediction': generated[i],
             'score': float(sample_score(opts.task, r['ans'], generated[i], r['update'])[0])}
            for i, r in enumerate(stage_rows[stage])
        ])
        atomic(out / 'quality_pool.json', quality_pool)

    result, predictions = evaluator(driver, train, [], [], [], 'final', stages[-1])
    append_jsonl(out / 'predictions.jsonl', predictions)
    atomic(out / 'metrics.json', [result])
    complete = {
        'status': 'complete', 'method': 'ours_v5_quality_replay', 'task': opts.task,
        'events': len(train), 'totals': totals, 'quality_pool_size': len(quality_pool),
        'elapsed_seconds': time.perf_counter() - started,
        'backend': driver.backend.metadata,
    }
    atomic(out / 'completed.json', complete)
    atomic(out / 'progress.json', {'status': 'complete', 'events': len(train), 'totals': totals})
    return complete


def main():
    opts = parse_args()
    # Evaluation writes the method name into progress/final metrics.  The
    # standalone candidate has no run_task parser, so set it explicitly.
    opts.method = 'ours_v5_quality_replay'
    # Keep tokenizer/collation overhead bounded on the rank processes.  The
    # shared TRACE runner uses the same setting for its full-stream jobs.
    import torch
    torch.set_num_threads(4)
    train, payload = load_data(opts.task, opts.smoke)
    out = opts.output_dir
    args = make_backend_args(opts, out)
    backend = TraceBackend(args)
    if backend.rank:
        runner.serve_backend(backend)
    else:
        driver = runner.BackendCoordinator(backend)
        try:
            result = run(opts, driver, train, payload)
            assert result['status'] == 'complete'
        finally:
            driver.shutdown()
    if dist.is_initialized():
        dist.destroy_process_group()


if __name__ == '__main__':
    main()
