#!/usr/bin/env python3
"""Run a conservative Qwen3 CrispEdit transfer on the shared WikiBigEdit protocol.

This runner uses Qwen3-specific KFAC projection files generated by
``build_crispedit_stats.py``.  It intentionally labels the current layer choice
as unvalidated until a Qwen3 layer sweep is completed.  The implementation is
the fixed-pretraining-curvature variant: edit-aware cache recomputation from
the upstream sequential script is not silently approximated.
"""

from __future__ import annotations

import argparse
import random
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Mapping, Sequence

import torch
from torch.utils.data import DataLoader

from baselines.common import (
    AnswerOnlyDataset,
    append_jsonl,
    atomic_json,
    environment_metadata,
    fixed_panel,
    load_manifest,
    load_model,
    load_tokenizer,
    make_collator,
    manifest_panel,
    sha256_file,
)
from baselines.crispedit_core import (
    ProjectedAdam,
    UPSTREAM_COMMIT,
    UPSTREAM_REPOSITORY,
    model_identity,
    module_name_for_layer,
    parameter_name_for_layer,
    parse_layers,
    projection_filename,
    resolve_parameters,
    validate_projection_payload,
)
from baselines.run_lora_family import evaluate_and_write
from baselines.editor_checkpoint import resume_identity, restore_stage, save_stage


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model-dir", type=Path, default=Path("Qwen3-8B-Base"))
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--stats-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--layers", type=str, required=True)
    parser.add_argument("--gpu", type=int, default=4)
    parser.add_argument("--seed", type=int, default=69)
    parser.add_argument("--energy-threshold", type=float, default=0.99)
    parser.add_argument("--epochs", type=int, default=25)
    parser.add_argument("--loss-threshold", type=float, default=1e-2)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--eval-batch-size", type=int, default=48)
    parser.add_argument("--learning-rate", type=float, default=5e-4)
    parser.add_argument("--weight-decay", type=float, default=0.0)
    parser.add_argument(
        "--max-grad-norm",
        type=float,
        default=0.0,
        help="0 disables clipping, matching upstream CrispEdit",
    )
    parser.add_argument("--max-length", type=int, default=128)
    parser.add_argument("--max-new-tokens", type=int, default=16)
    parser.add_argument(
        "--max-edits",
        type=int,
        default=0,
        help="take the frozen manifest prefix; 0 uses all selected edits",
    )
    parser.add_argument(
        "--chunk-size",
        type=int,
        default=0,
        help="0 runs breadth-first on all selected edits; positive values make sequential chunks",
    )
    parser.add_argument(
        "--eval-every-chunks",
        type=int,
        default=0,
        help="0 evaluates only after the final chunk",
    )
    parser.add_argument("--locality-panel-size", type=int, default=0)
    parser.add_argument("--multihop-panel-size", type=int, default=0)
    parser.add_argument("--skip-base-eval", action="store_true")
    parser.add_argument("--skip-eval", action="store_true")
    parser.add_argument("--allow-existing-output", action="store_true")
    parser.add_argument("--resume", action="store_true", help="Restore the last committed stage, including optimizer/RNG and prediction offsets")
    parser.add_argument("--dev-selection", type=Path, help="Hash-bound independent-dev layer selection certificate")
    parser.add_argument(
        "--allow-diagnostic-stats",
        action="store_true",
        help="allow a cache built from WikiBigEdit edit text rather than the Wikipedia old-task corpus",
    )
    parser.add_argument(
        "--preset-label",
        type=str,
        default="qwen25-depth-transfer-unvalidated",
    )
    return parser.parse_args()


def set_seed(seed: int) -> None:
    random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)


def split_chunks(rows: Sequence[dict[str, Any]], chunk_size: int) -> list[list[dict[str, Any]]]:
    if chunk_size <= 0:
        return [list(rows)]
    return [list(rows[start : start + chunk_size]) for start in range(0, len(rows), chunk_size)]


def load_projections(
    stats_dir: Path,
    layers: Sequence[int],
    parameters: Mapping[int, torch.nn.Parameter],
    identity: Mapping[str, Any],
    energy_threshold: float,
    *,
    allow_diagnostic_stats: bool,
) -> tuple[dict[torch.nn.Parameter, dict[str, torch.Tensor]], list[dict[str, Any]]]:
    caches: dict[torch.nn.Parameter, dict[str, torch.Tensor]] = {}
    provenance: list[dict[str, Any]] = []
    for layer in layers:
        path = stats_dir / projection_filename(layer, energy_threshold)
        if not path.is_file():
            raise FileNotFoundError(
                f"missing Qwen3 CrispEdit projection {path}; run build_crispedit_stats.py first"
            )
        payload = torch.load(path, map_location="cpu")
        validate_projection_payload(
            payload,
            identity=identity,
            layer=layer,
            energy_threshold=energy_threshold,
        )
        source_corpus = payload.get("source_corpus", {})
        if (source_corpus.get("publication_ready") is not True
                and source_corpus.get("verified_dated_corpus_transfer") is not True
                and not allow_diagnostic_stats):
            raise ValueError(
                f"layer {layer} uses diagnostic stats ({source_corpus.get('kind')}); "
                "pass --allow-diagnostic-stats only for a smoke test"
            )
        parameter = parameters[layer]
        Ua = payload["Ua"]
        Ub = payload["Ub"]
        mask = payload["mask"]
        expected_ua = (parameter.shape[1], parameter.shape[1])
        expected_ub = (parameter.shape[0], parameter.shape[0])
        expected_mask = (parameter.shape[1], parameter.shape[0])
        if tuple(Ua.shape) != expected_ua:
            raise ValueError(f"layer {layer} Ua shape {tuple(Ua.shape)} != {expected_ua}")
        if tuple(Ub.shape) != expected_ub:
            raise ValueError(f"layer {layer} Ub shape {tuple(Ub.shape)} != {expected_ub}")
        if tuple(mask.shape) != expected_mask:
            raise ValueError(f"layer {layer} mask shape {tuple(mask.shape)} != {expected_mask}")
        caches[parameter] = {
            "Ua": Ua.to(device=parameter.device, dtype=parameter.dtype),
            "Ub": Ub.to(device=parameter.device, dtype=parameter.dtype),
            # Keep the on-device mask in the matmul dtype to avoid a 50M-entry
            # conversion at every optimizer step.
            "mask": mask.to(device=parameter.device, dtype=parameter.dtype),
        }
        provenance.append(
            {
                "layer": layer,
                "path": str(path.resolve()),
                "file_sha256": sha256_file(path),
                "source_stats_file": payload.get("source_stats_file"),
                "source_corpus": source_corpus,
                "rank": payload.get("rank"),
                "total_directions": payload.get("total_directions"),
                "allowed_low_curvature_directions": payload.get(
                    "allowed_low_curvature_directions"
                ),
                "storage_dtype": payload.get("storage_dtype"),
            }
        )
    return caches, provenance


def train_epoch(
    model: torch.nn.Module,
    tokenizer: Any,
    rows: Sequence[dict[str, Any]],
    optimizer: ProjectedAdam,
    device: torch.device,
    *,
    seed: int,
    batch_size: int,
    max_length: int,
    max_grad_norm: float,
) -> dict[str, Any]:
    dataset = AnswerOnlyDataset(rows, tokenizer, max_length)
    generator = torch.Generator().manual_seed(seed)
    loader = DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=True,
        generator=generator,
        collate_fn=make_collator(tokenizer),
        num_workers=0,
        pin_memory=True,
    )
    model.train()
    model.config.use_cache = False
    loss_sum = 0.0
    example_count = 0
    answer_tokens = 0
    sequence_tokens = 0
    started = time.perf_counter()
    for batch in loader:
        batch = {key: value.to(device, non_blocking=True) for key, value in batch.items()}
        optimizer.zero_grad(set_to_none=True)
        outputs = model(**batch, use_cache=False)
        loss = outputs.loss
        loss.backward()
        if max_grad_norm > 0:
            torch.nn.utils.clip_grad_norm_(
                [parameter for parameter in model.parameters() if parameter.requires_grad],
                max_grad_norm,
            )
        optimizer.step()
        count = int(batch["input_ids"].shape[0])
        loss_sum += float(loss.detach()) * count
        example_count += count
        answer_tokens += int((batch["labels"] != -100).sum())
        sequence_tokens += int(batch["attention_mask"].sum())
    torch.cuda.synchronize(device)
    return {
        "loss": loss_sum / max(example_count, 1),
        "examples": example_count,
        "answer_tokens": answer_tokens,
        "sequence_tokens": sequence_tokens,
        "optimizer_steps": len(loader),
        "wall_seconds": time.perf_counter() - started,
    }


def main() -> None:
    args = parse_args()
    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is required")
    if args.output_dir.exists() and any(args.output_dir.iterdir()) and not args.allow_existing_output and not args.resume:
        raise FileExistsError(args.output_dir)
    if args.epochs <= 0 or args.batch_size <= 0:
        raise ValueError("epochs and batch size must be positive")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    layers = parse_layers(args.layers)
    selection = None
    if args.dev_selection:
        from baselines.editor_dev_selection import verify_selection
        selection = verify_selection(args.dev_selection, args, "CrispEdit-Qwen3-transfer", layers)
    set_seed(args.seed)
    torch.cuda.set_device(args.gpu)
    device = torch.device(f"cuda:{args.gpu}")
    rows, manifest_metadata = load_manifest(args.manifest)
    if args.max_edits > 0:
        rows = rows[: args.max_edits]
    if not rows:
        raise ValueError("no WikiBigEdit rows selected")
    chunks = split_chunks(rows, args.chunk_size)
    locality_panel = manifest_panel(
        manifest_metadata, "locality", limit=args.locality_panel_size
    ) or fixed_panel(rows, "loc", "loc_ans", args.locality_panel_size, args.seed + 1001)
    multihop_panel = manifest_panel(
        manifest_metadata, "mhop", limit=args.multihop_panel_size
    ) or fixed_panel(rows, "mhop", "mhop_ans", args.multihop_panel_size, args.seed + 2001)

    tokenizer = load_tokenizer(args.model_dir)
    model = load_model(args.model_dir, device)
    for parameter in model.parameters():
        parameter.requires_grad = False
    parameters = resolve_parameters(model, layers)
    for parameter in parameters.values():
        parameter.requires_grad = True
    identity = model_identity(args.model_dir)
    caches, projection_provenance = load_projections(
        args.stats_dir,
        layers,
        parameters,
        identity,
        args.energy_threshold,
        allow_diagnostic_stats=args.allow_diagnostic_stats,
    )
    originals = {layer: parameter.detach().cpu().clone() for layer, parameter in parameters.items()}
    optimizer = ProjectedAdam(
        list(parameters.values()),
        caches,
        lr=args.learning_rate,
        weight_decay=args.weight_decay,
    )
    qualified_corpus = all(
        p["source_corpus"].get("publication_ready") is True or
        p["source_corpus"].get("verified_dated_corpus_transfer") is True
        for p in projection_provenance
    )
    corpus_label = ("20220301 sampled-clone, whitespace-normalized" if all(
        p["source_corpus"].get("verified_dated_corpus_transfer") is True for p in projection_provenance
    ) else "Wikipedia corpus" if qualified_corpus else "diagnostic corpus")

    config = {
        **vars(args),
        "model_dir": str(args.model_dir.resolve()),
        "manifest": str(args.manifest.resolve()),
        "stats_dir": str(args.stats_dir.resolve()),
        "output_dir": str(args.output_dir.resolve()),
        "dev_selection": str(args.dev_selection.resolve()) if args.dev_selection else None,
        "manifest_sha256": sha256_file(args.manifest),
        "manifest_protocol_id": manifest_metadata.get("protocol_id"),
        "method": "CrispEdit-Qwen3-transfer",
        "method_variant": "fixed-pretraining-curvature",
        "upstream_repository": UPSTREAM_REPOSITORY,
        "upstream_commit": UPSTREAM_COMMIT,
        "upstream_qwen25_layers": [15, 16, 17, 18, 19],
        "qwen3_layers": layers,
        "qwen3_layer_selection_validated": selection is not None,
        "dev_selection_audit": selection,
        "model_identity": identity,
        "preset_label": args.preset_label,
        "publication_ready": bool(selection and qualified_corpus),
        "formal_baseline_eligible": bool(selection and qualified_corpus),
        "reproduction_exact": False,
        "method_display_name": f"CrispEdit ({corpus_label}, Qwen3 " + ("dev-tuned transfer)" if selection else "dev candidate)"),
        "publication_blocker": None if selection and qualified_corpus else "Independent Qwen3 dev layer selection and verified dated-corpus statistics are required.",
        "qualification": f"{corpus_label}, Qwen3 transfer; fixed pretraining curvature; not canonical source-corpus or official Qwen3 preset reproduction",
        "projection_policy": "fixed_pretraining_curvature",
        "dynamic_edit_cache_recomputation": False,
        "projection_provenance": projection_provenance,
        "edited_parameters": [parameter_name_for_layer(layer) for layer in layers],
        "trainable_parameters": sum(parameter.numel() for parameter in parameters.values()),
        "num_facts": len(rows),
        "num_chunks": len(chunks),
        "closed_book_evaluation": True,
        "prompt_template": "Question: <question>\\nAnswer:",
        "answer_loss_only": True,
        "created_at": datetime.now(timezone.utc).isoformat(),
        **environment_metadata(),
    }
    identity_for_resume = resume_identity(args, config["manifest_sha256"], identity, projection_provenance,
        ["baselines/run_crispedit.py", "baselines/crispedit_core.py", "baselines/editor_dev_selection.py"])
    config["resume_identity"] = identity_for_resume
    if args.resume:
        import json
        original_config = json.loads((args.output_dir / "run_config.json").read_text())
        if original_config.get("resume_identity") != identity_for_resume:
            raise ValueError("CrispEdit run configuration changed across resume")
        config = original_config
    else:
        atomic_json(args.output_dir / "run_config.json", config)
    metrics: list[dict[str, Any]] = []
    training_log: list[dict[str, Any]] = []
    seen: list[dict[str, Any]] = []
    start_chunk = 0
    if args.resume:
        checkpoint = restore_stage(args.output_dir, parameters, optimizer, identity_for_resume)
        start_chunk = checkpoint["cursor"]
        if sum(len(chunk) for chunk in chunks[:start_chunk]) != checkpoint["seen_count"]:
            raise ValueError("CrispEdit checkpoint chunk cursor mismatch")
        seen = list(rows[:checkpoint["seen_count"]])
        metrics, training_log = checkpoint["metrics"], checkpoint["training_log"]
        print({"resumed_from_chunk": start_chunk, "seen_count": len(seen)}, flush=True)
        del checkpoint
    if not args.resume and not args.skip_eval and not args.skip_base_eval:
        metrics.append(
            evaluate_and_write(
                model,
                tokenizer,
                rows,
                locality_panel,
                multihop_panel,
                device,
                args,
                checkpoint="base",
                current_stage=None,
            )
        )
        atomic_json(args.output_dir / "metrics.json", metrics)

    torch.cuda.reset_peak_memory_stats(device)
    started = time.time()
    for chunk_index, current in enumerate(chunks[start_chunk:], start_chunk + 1):
        epoch_records: list[dict[str, Any]] = []
        for epoch in range(1, args.epochs + 1):
            record = train_epoch(
                model,
                tokenizer,
                current,
                optimizer,
                device,
                seed=args.seed + chunk_index * 1000 + epoch,
                batch_size=args.batch_size,
                max_length=args.max_length,
                max_grad_norm=args.max_grad_norm,
            )
            record["epoch"] = epoch
            epoch_records.append(record)
            if record["loss"] < args.loss_threshold:
                break
        seen.extend(current)
        chunk_record = {
            "chunk": chunk_index,
            "num_current_facts": len(current),
            "num_seen_facts": len(seen),
            "first_sample_id": current[0]["sample_id"],
            "last_sample_id": current[-1]["sample_id"],
            "epochs": epoch_records,
        }
        training_log.append(chunk_record)
        atomic_json(args.output_dir / "training_log.json", training_log)
        should_evaluate = (
            not args.skip_eval
            and (
                chunk_index == len(chunks)
                or (
                    args.eval_every_chunks > 0
                    and chunk_index % args.eval_every_chunks == 0
                )
            )
        )
        if should_evaluate:
            current_stage = max(int(row["stage"]) for row in seen)
            result = evaluate_and_write(
                model,
                tokenizer,
                seen,
                locality_panel,
                multihop_panel,
                device,
                args,
                checkpoint=f"chunk_{chunk_index:04d}",
                current_stage=current_stage,
            )
            result["train"] = chunk_record
            metrics.append(result)
            atomic_json(args.output_dir / "metrics.json", metrics)
        save_stage(args.output_dir, parameters, optimizer, identity_for_resume,
                   cursor=chunk_index, seen_count=len(seen),
                   stage=max(int(row["stage"]) for row in seen),
                   metrics=metrics, training_log=training_log)

    deltas = {
        parameter_name_for_layer(layer): parameter.detach().cpu() - originals[layer]
        for layer, parameter in parameters.items()
    }
    torch.save(
        {
            "format": "multi-parameter-delta/v1",
            "base_model": str(args.model_dir.resolve()),
            "method": "CrispEdit-Qwen3-transfer",
            "layers": layers,
            "deltas": deltas,
        },
        args.output_dir / "crispedit_delta.pt",
    )
    atomic_json(args.output_dir / "training_log.json", training_log)
    if metrics:
        atomic_json(args.output_dir / "metrics.json", metrics)
    atomic_json(
        args.output_dir / "completed.json",
        {
            "status": "complete",
            "elapsed_seconds": time.time() - started,
            "peak_vram_gb": torch.cuda.max_memory_allocated(device) / (1024**3),
            "num_facts": len(rows),
            "num_chunks": len(chunks),
            "final_stage": max(int(row["stage"]) for row in rows),
            "edits": len(rows),
            "qwen3_layer_selection_validated": selection is not None,
            "formal_baseline_eligible": config["formal_baseline_eligible"],
            "resumed_from_chunk": start_chunk,
        },
    )


if __name__ == "__main__":
    main()
