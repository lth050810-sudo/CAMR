        '--learning-rate', '2e-6', '--steps-per-event', '1', '--seed', '42',
        '--fsdp-sharding-strategy', 'full_shard', '--max-length', str(p_limit + a_limit),
        '--max-new-tokens', str(gen_limit), '--eval-batch-size', str(eval_batch),
        '--log-every', '10', '--skip-base-eval', '--no-stage-eval',
